"""Acceptance Test B4: Provider Swap and Architecture Isolation.

Verifies:
1. The service runs end-to-end with ASR_PROVIDER=stub without any provider-specific code
   outside backend/asr/meetmind_asr/providers/.
2. Static AST check: changing/adding providers requires touching ONLY settings (config.py)
   and backend/asr/meetmind_asr/providers/. No other module in meetmind_asr imports
   from concrete provider implementations.
"""

from __future__ import annotations

import ast
import asyncio
import json
import uuid
from pathlib import Path

import pytest
import websockets
from conftest import ServerHarness, exchange_ws_ticket, make_pcm16_chunk
from meetmind_schemas.keys import events_stream_key

pytestmark = [pytest.mark.integration, pytest.mark.timeout(60)]


def test_b4_static_provider_isolation() -> None:
    """Assert no file outside providers/ and config.py imports concrete provider classes."""
    asr_pkg = Path(__file__).resolve().parents[2] / "meetmind_asr"
    assert asr_pkg.exists(), f"meetmind_asr package not found at {asr_pkg}"

    allowed_files_for_concrete_providers = {
        asr_pkg / "providers" / "deepgram.py",
        asr_pkg / "providers" / "stub.py",
        asr_pkg / "providers" / "__init__.py",
    }

    forbidden_names = {"DeepgramProvider", "StubProvider", "build_deepgram_url", "StubFaultConfig"}

    for py_file in asr_pkg.rglob("*.py"):
        if py_file in allowed_files_for_concrete_providers:
            continue

        tree = ast.parse(py_file.read_text(encoding="utf-8"), filename=str(py_file))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    assert not any(alias.name.endswith(f".{f}") for f in ["deepgram", "stub"]), (
                        f"{py_file.name} directly imports provider module {alias.name}"
                    )
            elif isinstance(node, ast.ImportFrom):
                mod = node.module or ""
                if "providers.deepgram" in mod or "providers.stub" in mod:
                    pytest.fail(f"{py_file.name} directly imports from {mod}")
                for alias in node.names:
                    if alias.name in forbidden_names:
                        pytest.fail(
                            f"{py_file.name} imports concrete provider symbol '{alias.name}'"
                        )


@pytest.mark.asyncio
async def test_b4_runtime_stub_provider(
    gateway_harness: ServerHarness,
    asr_worker_factory,
    real_redis,
) -> None:
    """Verifies end-to-end operation with ASR_PROVIDER=stub."""
    meeting_id = f"mtg_b4_{uuid.uuid4().hex[:8]}"
    tenant_id = gateway_harness.tenant_a

    _worker = await asr_worker_factory(provider="stub")

    admin_token = gateway_harness.jwks.mint_token(
        sub="admin_b4", org_id=gateway_harness.org_a, org_role="org:admin"
    )
    _, ingest_ticket_resp = await exchange_ws_ticket(
        gateway_harness.http_url, admin_token, meeting_id, role="ingest"
    )
    ingest_ticket = ingest_ticket_resp["ticket"]
    ingest_uri = f"{gateway_harness.ws_url}/v1/meetings/{meeting_id}/stream?ticket={ingest_ticket}"

    async with websockets.connect(ingest_uri) as ws_ingest:

        async def recv_ack():
            while True:
                msg = json.loads(await ws_ingest.recv())
                if msg.get("type") == "ack":
                    return msg

        await ws_ingest.send(
            json.dumps(
                {
                    "type": "control",
                    "action": "meeting_start",
                    "adapter_type": "chrome_extension",
                }
            )
        )
        assert (await recv_ack())["status"] == "accepted"

        await ws_ingest.send(
            json.dumps(
                {
                    "type": "control",
                    "action": "consent_confirmed",
                    "consent_type": "audio_capture",
                    "external_participants": True,
                    "jurisdiction_hint": "GDPR",
                    "consent_text_version": "v2.0",
                    "client_version": "2.1.0",
                }
            )
        )
        assert (await recv_ack())["status"] == "accepted"

        t_base = 4_000_000
        for seq in range(1, 8):
            frame = make_pcm16_chunk(seq=seq, ts_ms=t_base + seq * 100)
            await ws_ingest.send(frame)
            ack = await recv_ack()
            assert ack.get("status") in ("accepted", "acked")

    # Verify finals were generated by stub provider
    ev_key = events_stream_key(tenant_id, meeting_id)
    events = []
    for _ in range(30):
        raw_events = await real_redis.xrange(ev_key)
        for _, fields in raw_events:
            p_raw = fields.get(b"payload") or fields.get("payload")
            if p_raw:
                payload = json.loads(p_raw.decode() if isinstance(p_raw, bytes) else p_raw)
                if payload.get("event_type") == "transcript_final":
                    events.append(payload)
        if len(events) >= 2:
            break
        await asyncio.sleep(0.2)

    assert len(events) >= 2
    assert events[0]["payload"]["provider"] == "stub"
